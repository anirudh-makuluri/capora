import { readFile, writeFile, mkdir } from 'node:fs/promises';
const names = [
  'CaporaUSD',
  'AgentWallet',
  'WalletFactory',
  'PurchaseEscrow',
  'TestMarket',
  'ManagedFund',
  'LendingPool',
  'PublicChit',
  'BankFactory',
];
const declarations = [];
for (const name of names) {
  const file = name === 'WalletFactory' ? 'AgentWallet' : name;
  const artifact = JSON.parse(
    await readFile(new URL(`../artifacts/contracts/${file}.sol/${name}.json`, import.meta.url), 'utf8'),
  );
  declarations.push(`export const ${name}Abi = ${JSON.stringify(artifact.abi)} as const;`);
}
await mkdir(new URL('../src/', import.meta.url), { recursive: true });
await writeFile(
  new URL('../src/abis.ts', import.meta.url),
  `// Generated by pnpm --filter @capora/bank build. Do not edit.\n${declarations.join('\n')}`,
);
